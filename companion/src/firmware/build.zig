//! Companion firmware build glue on the firmware of this repository. The board
//! table and the firmware recipe come from `keyboards/`; this file adds the
//! companion's board inventory, its default keymap module and project
//! builds. It schedules no process runs and no device access.
const std = @import("std");

const keyboards = @import("zigmkay_firmware").keyboards;
pub const boards = @import("boards.zig").Inventory(keyboards.boards.boards);

/// Source locations inside the firmware package.
pub const Sources = keyboards.Sources;

/// Build one board entrypoint with its default keymap or `supplied_keymap`.
///
/// Each call creates its own `zigmkay` and `zkeycodes` modules: `add_app_import`
/// wires the firmware's microzig into them, so sharing one instance between
/// firmwares would put two microzig modules into one graph. The root module
/// imports `zigmkay`, `zkeycodes` and `keymap`. Callers may replace `keymap`
/// afterwards with `add_app_import("keymap", module, .{})`.
pub fn addKeyboardFirmware(
    b: *std.Build,
    mb: anytype,
    target: anytype,
    optimize: std.builtin.OptimizeMode,
    name: []const u8,
    board: @import("boards.zig").Entry,
    sources: Sources,
    supplied_keymap: ?std.Build.LazyPath,
) *@TypeOf(mb.*).Firmware {
    return keyboards.addKeyboardFirmware(b, mb, target, optimize, name, .{
        .name = board.name,
        .root_source_file = board.root_source_file,
        .keymap = board.default_keymap,
    }, sources, supplied_keymap);
}

/// The portable default keymap inventory: one host module exposing `boards`,
/// `profiles` (the default keymap of each board, in `boards.entries` order) and
/// `processing_descriptors`. Its import table holds `zigmkay = processor` and
/// `zkeycodes = keycodes`, so callers can share them with
/// `.import_table.get("zkeycodes")`. `keycodes` must import `processor` as
/// `zigmkay`. Call it once per build graph and reuse the module.
///
/// One module owns all default keymaps because several share relative imports
/// (`keymap_shared.zig`), and a file may belong to only one module.
pub fn defaultKeymaps(b: *std.Build, sources: Sources, processor: *std.Build.Module, keycodes: *std.Build.Module) *std.Build.Module {
    const files = b.addWriteFiles();
    var copied: std.StringArrayHashMapUnmanaged(void) = .empty;
    for (boards.entries) |board| copied.put(b.allocator, board.default_keymap, {}) catch @panic("OOM");
    for (@import("boards.zig").default_keymap_support) |path| copied.put(b.allocator, path, {}) catch @panic("OOM");
    for (copied.keys()) |path| _ = files.addCopyFile(sources.keyboards.path(b, path), b.fmt("keyboards/{s}", .{path}));
    _ = files.addCopyFile(sources.keyboards.path(b, "boards.zig"), "firmware_boards.zig");
    _ = files.add("boards.zig", @embedFile("boards.zig"));
    _ = files.add("processing_descriptors.zig", @embedFile("processing_descriptors.zig"));
    _ = files.add("default_keymaps.zig", defaultKeymapsSource(b));
    return b.createModule(.{
        .root_source_file = files.getDirectory().path(b, "default_keymaps.zig"),
        .imports = &.{
            .{ .name = "zigmkay", .module = processor },
            .{ .name = "zkeycodes", .module = keycodes },
        },
    });
}

fn defaultKeymapsSource(b: *std.Build) []const u8 {
    var text: std.ArrayList(u8) = .empty;
    text.appendSlice(b.allocator,
        \\//! Generated by the companion firmware adapter: the default keymap of
        \\//! each selected board, in `boards.entries` order.
        \\pub const boards = @import("boards.zig").Inventory(@import("firmware_boards.zig").boards);
        \\pub const processing_descriptors = @import("processing_descriptors.zig");
        \\pub const profiles = [_]type{
        \\
    ) catch @panic("OOM");
    // Zig requires literal import operands, so the inventory is generated.
    for (boards.entries) |board|
        text.print(b.allocator, "    @import(\"keyboards/{s}\"), // {s}\n", .{ board.default_keymap, board.name }) catch @panic("OOM");
    text.appendSlice(b.allocator,
        \\};
        \\comptime {
        \\    if (profiles.len != boards.entries.len) @compileError("Default keymap inventory is out of date");
        \\}
        \\test {
        \\    _ = @import("boards.zig");
        \\    _ = processing_descriptors;
        \\}
        \\
    ) catch @panic("OOM");
    return text.items;
}

/// The firmware of the board `board_name` with the keymap of the frozen
/// project export at the absolute `export_path`. Part of the runtime closure.
pub fn projectFirmware(
    b: *std.Build,
    mb: anytype,
    target: anytype,
    sources: Sources,
    board_name: []const u8,
    export_path: []const u8,
) *@TypeOf(mb.*).Firmware {
    const board = boards.find(board_name) orelse std.debug.panic("Unknown firmware board selector '{s}'", .{board_name});
    const firmware = addKeyboardFirmware(b, mb, target, .safe, "project", board, sources, null);
    const processor = firmware.exe.root_module.import_table.get("zigmkay").?;
    const keycodes = firmware.exe.root_module.import_table.get("zkeycodes").?;
    const layout = b.createModule(.{ .root_source_file = b.path("src/layout/root.zig"), .imports = &.{.{ .name = "zigmkay", .module = processor }} });
    const selected = @import("../project/build_input.zig").load(b, export_path, processor, keycodes, layout) catch |err|
        std.debug.panic("Cannot verify embedded export: {t}", .{err});
    selected.module.addImport("microzig", firmware.core_mod);
    firmware.add_app_import("keymap", selected.module, .{});
    return firmware;
}

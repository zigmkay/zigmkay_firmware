//! Regenerates the Tutor's English word list, `src/desktop/tutor_words_en.txt`,
//! from three pinned downloads. Run it only on purpose:
//!
//!     zig build gen-tutor-words -- <download dir>
//!
//! The directory holds the files named in `inputs`; each one is checked
//! against its SHA-256 before use. Words are ranked by how often they occur
//! in film and TV subtitles (FrequencyWords), kept only when SCOWL up to size
//! 50 lists them in lower case (which drops names and transcription noise),
//! and dropped when a blocklist names them. The header records the sources,
//! their licenses and the letter order the Tutor unlocks letters in.
const std = @import("std");

const Input = struct {
    file: []const u8,
    sha256: []const u8,
    url: []const u8,
    max_bytes: usize,
};

const frequency_input: Input = .{
    .file = "en_50k.txt",
    .sha256 = "5351ff405b1126ef555791dd4d9798a48e3e9a501a9fc481a9da957752cfb458",
    .url = "https://raw.githubusercontent.com/hermitdave/FrequencyWords/525f9b560de45753a5ea01069454e72e9aa541c6/content/2018/en/en_50k.txt",
    .max_bytes = 4 << 20,
};
const scowl_input: Input = .{
    .file = "scowl-2020.12.07.tar.gz",
    .sha256 = "5587667caa20c4891390c2d42dbb4d5c4c3f41bee77af1457ece3ba23fb859cc",
    .url = "https://downloads.sourceforge.net/wordlist/scowl-2020.12.07.tar.gz",
    .max_bytes = 16 << 20,
};
const blocklist_input: Input = .{
    .file = "ldnoobw-en",
    .sha256 = "af851ecef1d5f212caba17339b12ac39cc2fef7d78c74876f67237644fcee8bd",
    .url = "https://raw.githubusercontent.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words/5faf2ba42d7b1c0977169ec3611df25a3c08eb13/en",
    .max_bytes = 1 << 20,
};
const inputs = [_]Input{ frequency_input, scowl_input, blocklist_input };

/// SCOWL lists up to size 50, the size of a typical spell checker; larger
/// sizes add rare words and, from size 80, parts with other license terms.
const scowl_lists = [_][]const u8{
    "english-words.10", "english-words.20", "english-words.35", "english-words.40", "english-words.50",
    "american-words.10", "american-words.20", "american-words.35", "american-words.40", "american-words.50",
};

const min_len = 3;
const max_len = 14;
const max_words = 30_000;
/// The first letters are the set of this many letters that forms the most of
/// the `first_pool` most frequent words; each later letter is the one that
/// adds the most of the `later_pool` most frequent words.
const first_letters = 6;
const first_pool = 3_000;
const later_pool = 10_000;
/// Letters considered for the first set, most frequent first.
const first_candidates = 16;

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 4) {
        std.debug.print("usage: gen-tutor-words <download dir> <deny list> <output>\n", .{});
        return error.Usage;
    }
    var dir = std.Io.Dir.cwd().openDir(io, args[1], .{}) catch |err| {
        std.debug.print("cannot open the download directory {s}: {t}\n", .{ args[1], err });
        printDownloads();
        return err;
    };
    defer dir.close(io);

    var bytes: [inputs.len][]const u8 = undefined;
    for (inputs, &bytes) |input, *out| out.* = try readPinned(a, io, dir, input);

    const vocabulary = try scowlVocabulary(a, bytes[1]);
    var blocked: std.StringHashMapUnmanaged(void) = .empty;
    try addWords(a, &blocked, bytes[2]);
    const deny = try std.Io.Dir.cwd().readFileAlloc(io, args[2], a, .limited(1 << 20));
    try addWords(a, &blocked, deny);
    const roots = try denyRoots(a, deny);

    var words: std.ArrayList([]const u8) = .empty;
    var lines = std.mem.splitScalar(u8, bytes[0], '\n');
    while (lines.next()) |line| {
        const word = std.mem.sliceTo(std.mem.trimEnd(u8, line, "\r"), ' ');
        if (word.len < min_len or word.len > max_len or !isLowerAscii(word)) continue;
        if (!vocabulary.contains(word) or blocked.contains(word)) continue;
        if (for (roots) |root| {
            if (std.mem.indexOf(u8, word, root) != null) break true;
        } else false) continue;
        try words.append(a, word);
        if (words.items.len == max_words) break;
    }

    var order: [26]u8 = undefined;
    letterOrder(words.items, &order);

    var out: std.Io.Writer.Allocating = .init(a);
    const w = &out.writer;
    try w.print(
        \\# Zigmkay Tutor English word list: {d} words, most frequent first.
        \\# Generated by companion/tools/gen_tutor_words.zig; do not edit by hand.
        \\# Regenerate with `zig build gen-tutor-words -- <download dir>`.
        \\#
        \\# Words are lower-case a-z, {d}-{d} letters long.
        \\# Ranking: FrequencyWords en_50k (OpenSubtitles 2018) by Hermit Dave,
        \\#   licensed CC BY-SA 4.0, https://creativecommons.org/licenses/by-sa/4.0/
        \\#   {s}
        \\#   sha256 {s}
        \\# Vocabulary: SCOWL 2020.12.07 up to size 50 (english and american),
        \\#   lower-case entries only. Copyright 2000-2018 by Kevin Atkinson and
        \\#   others; see licenses/SCOWL-Copyright.txt.
        \\#   {s}
        \\#   sha256 {s}
        \\# Removed: words in the LDNOOBW English list (CC BY 4.0,
        \\#   https://creativecommons.org/licenses/by/4.0/) and in
        \\#   companion/tools/tutor_words_deny.txt.
        \\#   {s}
        \\#   sha256 {s}
        \\# Changes: filtered to the SCOWL vocabulary, blocked words removed,
        \\#   counts dropped, at most {d} words kept. This list is licensed
        \\#   CC BY-SA 4.0 like its ranking source.
        \\#
        \\# letter order: {s}
        \\
    , .{
        words.items.len,
        min_len,
        max_len,
        frequency_input.url,
        frequency_input.sha256,
        scowl_input.url,
        scowl_input.sha256,
        blocklist_input.url,
        blocklist_input.sha256,
        max_words,
        order[0..],
    });
    for (words.items) |word| try w.print("{s}\n", .{word});
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = args[3], .data = out.written() });
    std.debug.print("wrote {d} words to {s}; letter order {s}\n", .{ words.items.len, args[3], order[0..] });
}

fn printDownloads() void {
    std.debug.print("download these files into the directory first:\n", .{});
    for (inputs) |input| std.debug.print("  {s}  <-  {s}\n", .{ input.file, input.url });
}

fn readPinned(a: std.mem.Allocator, io: std.Io, dir: std.Io.Dir, input: Input) ![]const u8 {
    const bytes = dir.readFileAlloc(io, input.file, a, .limited(input.max_bytes)) catch |err| {
        std.debug.print("cannot read {s}: {t}\n", .{ input.file, err });
        printDownloads();
        return err;
    };
    var digest: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
    const hex = std.fmt.bytesToHex(digest, .lower);
    if (!std.mem.eql(u8, &hex, input.sha256)) {
        std.debug.print("{s} has sha256 {s}, expected {s} from {s}\n", .{ input.file, &hex, input.sha256, input.url });
        return error.InputHashMismatch;
    }
    return bytes;
}

fn isLowerAscii(word: []const u8) bool {
    for (word) |c| if (c < 'a' or c > 'z') return false;
    return true;
}

/// The lower-case words of the SCOWL lists up to size 50, read from the
/// release tarball.
fn scowlVocabulary(a: std.mem.Allocator, tarball: []const u8) !std.StringHashMapUnmanaged(void) {
    var input: std.Io.Reader = .fixed(tarball);
    var window: [std.compress.flate.max_window_len]u8 = undefined;
    var gzip: std.compress.flate.Decompress = .init(&input, .gzip, &window);
    var name_buf: [std.fs.max_path_bytes]u8 = undefined;
    var link_buf: [std.fs.max_path_bytes]u8 = undefined;
    var it: std.tar.Iterator = .init(&gzip.reader, .{ .file_name_buffer = &name_buf, .link_name_buffer = &link_buf });
    var words: std.StringHashMapUnmanaged(void) = .empty;
    var found: usize = 0;
    while (try it.next()) |file| {
        if (file.kind != .file) continue;
        const base = std.fs.path.basename(file.name);
        const wanted = for (scowl_lists) |list| {
            if (std.mem.eql(u8, base, list) and std.mem.endsWith(u8, std.fs.path.dirname(file.name) orelse "", "final")) break true;
        } else false;
        if (!wanted) continue;
        var content: std.Io.Writer.Allocating = .init(a);
        try it.streamRemaining(file, &content.writer);
        try addWords(a, &words, content.written());
        found += 1;
    }
    if (found != scowl_lists.len) return error.ScowlListsMissing;
    return words;
}

/// Adds every line of `text` that is a lower-case a-z word; `#` starts a comment.
fn addWords(a: std.mem.Allocator, set: *std.StringHashMapUnmanaged(void), text: []const u8) !void {
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = std.mem.trim(u8, std.mem.sliceTo(raw, '#'), " \t\r");
        if (line.len == 0 or !isLowerAscii(line)) continue;
        try set.put(a, line, {});
    }
}

/// The `*root` lines of the deny list: a word containing one is removed.
fn denyRoots(a: std.mem.Allocator, text: []const u8) ![]const []const u8 {
    var roots: std.ArrayList([]const u8) = .empty;
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = std.mem.trim(u8, raw, " \t\r");
        if (line.len < 2 or line[0] != '*' or !isLowerAscii(line[1..])) continue;
        try roots.append(a, line[1..]);
    }
    return roots.items;
}

fn maskOf(word: []const u8) u32 {
    var mask: u32 = 0;
    for (word) |c| mask |= @as(u32, 1) << @intCast(c - 'a');
    return mask;
}

fn formable(masks: []const u32, set: u32) usize {
    var n: usize = 0;
    for (masks) |m| n += @intFromBool(m & ~set == 0);
    return n;
}

/// Orders the alphabet by how many frequent words each step makes possible:
/// first the set of `first_letters` letters that forms the most frequent
/// words, then one letter at a time, each adding the most words. Ties go to
/// the letter that occurs more often.
fn letterOrder(words: []const []const u8, order: *[26]u8) void {
    var masks_buf: [later_pool]u32 = undefined;
    const pool = @min(words.len, later_pool);
    for (words[0..pool], masks_buf[0..pool]) |word, *m| m.* = maskOf(word);
    const masks = masks_buf[0..pool];

    var occurrences: [26]usize = @splat(0);
    for (words[0..pool]) |word| for (word) |c| {
        occurrences[c - 'a'] += 1;
    };
    var by_freq: [26]u8 = undefined;
    for (&by_freq, 0..) |*c, i| c.* = @intCast(i);
    std.mem.sort(u8, &by_freq, &occurrences, struct {
        fn more(occ: *const [26]usize, x: u8, y: u8) bool {
            return occ[x] > occ[y] or (occ[x] == occ[y] and x < y);
        }
    }.more);

    // The best first set among the most frequent letters.
    const first_masks = masks[0..@min(masks.len, first_pool)];
    var best_set: u32 = 0;
    var best_count: usize = 0;
    var pick: [first_letters]u8 = undefined;
    for (0..first_letters) |i| pick[i] = @intCast(i);
    while (true) {
        var set: u32 = 0;
        for (pick) |p| set |= @as(u32, 1) << @intCast(by_freq[p]);
        const count = formable(first_masks, set);
        if (count > best_count) {
            best_count = count;
            best_set = set;
        }
        // Next combination of `first_letters` out of `first_candidates`.
        var k: usize = first_letters;
        while (k > 0) {
            k -= 1;
            if (pick[k] < first_candidates - first_letters + k) break;
        } else break;
        if (pick[k] >= first_candidates - first_letters + k) break;
        pick[k] += 1;
        for (k + 1..first_letters) |j| pick[j] = pick[j - 1] + 1;
    }

    var len: usize = 0;
    for (by_freq) |c| if (best_set & (@as(u32, 1) << @intCast(c)) != 0) {
        order[len] = 'a' + c;
        len += 1;
    };
    var set = best_set;
    while (len < 26) : (len += 1) {
        var best: ?u8 = null;
        var best_gain: usize = 0;
        const base = formable(masks, set);
        for (by_freq) |c| {
            const bit = @as(u32, 1) << @intCast(c);
            if (set & bit != 0) continue;
            const gain = formable(masks, set | bit) - base;
            if (best == null or gain > best_gain) {
                best = c;
                best_gain = gain;
            }
        }
        order[len] = 'a' + best.?;
        set |= @as(u32, 1) << @intCast(best.?);
    }
}
